const 无扩展 = (p) => p.replace(/\.vue$/i, '');

// ---- 收集所有 vue 文件 ----
const walk = (dir, out = []) => {
    for (const name of fs.readdirSync(dir)) {
        const p = path.join(dir, name);
        if (fs.statSync(p).isDirectory()) walk(p, out);
        else if (name.endsWith('.vue')) out.push(p);
    }
    return out;
};
const 全部文件 = walk(配置.视图目录).filter(f => !/[\\/](layout|login|error|init)[\\/]/.test(f));
const 文件rel集合 = new Set(全部文件.map(f => 无扩展(posix.join(...path.relative(配置.视图目录, f).split(/[\\/]/)))));

// ---- 提取单文件可见文案 ----
const 提取文案 = (文件路径) => {
    const txt = fs.readFileSync(文件路径, 'utf8');
    const set = new Set();
    // 模板文本节点(排除插值与注释天然不匹配)
    for (const m of txt.matchAll(/>([^<>{}]{2,60})</g)) {
        const t = m[1].replace(/\s+/g, ' ').trim();
        if (t && !/^[\d\s.,:;()\-+/]+$/.test(t)) set.add(t);
    }
    // 常见属性文案
    for (const m of txt.matchAll(/(?:label|placeholder|title|content|text)="([^"{}]{2,60})"/g)) {
        const t = m[1].replace(/\s+/g, ' ').trim();
        if (t) set.add(t);
    }
    return [...set];
};

// ---- 解析 @/view 与相对路径两种 import,建依赖图 ----
const 文件文案 = new Map();
const 依赖图 = new Map();
for (const f of 全部文件) {
    const rel = 无扩展(posix.join(...path.relative(配置.视图目录, f).split(/[\\/]/)));
    文件文案.set(rel, 提取文案(f));
    const txt = fs.readFileSync(f, 'utf8');
    const deps = [];
    for (const m of txt.matchAll(/from\s+['"]([^'"]+)['"]/g)) {
        let spec = m[1];
        let relDep = null;
        if (spec.startsWith('@/view/')) relDep = 无扩展(spec.slice('@/view/'.length));
        else if (spec.startsWith('.')) relDep = 无扩展(posix.normalize(posix.join(posix.dirname(rel), spec)));
        if (relDep && 文件rel集合.has(relDep)) deps.push(relDep);
    }
    依赖图.set(rel, deps);
}

// 页面引用的组件(含组件套组件)的文案都归到该页面名下
const 收集组件文案 = (页面rel) => {
    const 词 = [];
    const 已访 = new Set([页面rel]);
    const 队列 = [...(依赖图.get(页面rel) || [])];
    while (队列.length) {
        const rel = 队列.shift();
        if (已访.has(rel)) continue;
        已访.add(rel);
        词.push(...(文件文案.get(rel) || []));
        队列.push(...(依赖图.get(rel) || []));
    }
    return 词;
};

// ---- 组装索引 ----
const 词条 = [];
const 收录页面 = ({路径, 名称, 分组}) => {
    if (词条.some(x => x.路径 === 路径)) return;
    const 文件rel = 配置.文件映射[路径] || 路径;
    const 词集 = new Set([
        ...(配置.别名表[路径] || []),
        ...(文件文案.get(文件rel) || []),
        ...收集组件文案(文件rel),
    ]);
    const 词 = [...词集].map(t => t.trim()).filter(Boolean).slice(0, 配置.每页词数上限);
    词条.push({路径, 名称, 分组, 词});
};

const 菜单 = JSON.parse(fs.readFileSync(配置.菜单文件, 'utf8'));
for (const 分组 of 菜单) {
    for (const 子 of 分组.children || []) {
        收录页面({路径: 子.path, 名称: 子.meta?.title || 子.name, 分组: 分组.meta?.title || 分组.name});
    }
}
配置.额外页面.forEach(收录页面);

fs.mkdirSync(path.dirname(配置.输出文件), {recursive: true});
fs.writeFileSync(配置.输出文件, JSON.stringify(词条));
const 总词数 = 词条.reduce((a, b) => a + b.词.length, 0);
console.log(`[搜索索引] ${词条.length} 个页面, ${总词数} 条词 → ${配置.输出文件}`);
